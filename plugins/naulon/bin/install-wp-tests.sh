#!/usr/bin/env bash
#
# Fetch WordPress and its PHPUnit test library, so the integration suite can run anywhere a PHP
# binary and a MySQL server exist — CI included.
#
# The suite in tests/integration is the only place two guarantees are proven against a real
# database: that a cached update manifest is re-validated against the pinned download host on every
# read (a regression there means WordPress unpacks and executes a zip an attacker named), and that
# deleting the plugin keeps the publisher's wallets and earnings. Until this script existed those
# tests ran only by hand, through wp-env, on one laptop.
#
# This is deliberately not the WP-CLI scaffold's install-wp-tests.sh: that one fetches the test
# library with `svn`, and Subversion is no longer present on GitHub's Ubuntu runners. Everything
# here comes over HTTPS as a tarball.
#
# Usage:
#   bin/install-wp-tests.sh [db-name] [db-user] [db-pass] [db-host] [wp-version]
#
# Environment:
#   WP_CORE_DIR   where WordPress lands       (default /tmp/naulon-wordpress)
#   WP_TESTS_DIR  where the test library lands (default /tmp/naulon-wordpress-tests-lib)
#   SKIP_DB_CREATE=1  the database already exists (a container's MYSQL_DATABASE, say)

set -euo pipefail

DB_NAME=${1:-wordpress_test}
DB_USER=${2:-root}
DB_PASS=${3:-root}
DB_HOST=${4:-127.0.0.1}
WP_VERSION=${5:-latest}

WP_CORE_DIR=${WP_CORE_DIR:-/tmp/naulon-wordpress}
WP_TESTS_DIR=${WP_TESTS_DIR:-/tmp/naulon-wordpress-tests-lib}
SKIP_DB_CREATE=${SKIP_DB_CREATE:-0}

PLUGIN_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
# The directory holding the plugin, i.e. the repo's plugins/. The test WordPress is pointed at it
# as WP_PLUGIN_DIR below, which is what lets the suite run against the working tree instead of a
# copy — see the note on that constant.
PLUGINS_ROOT=$(dirname "$PLUGIN_DIR")

say() { printf '\033[1m==>\033[0m %s\n' "$*"; }

# WordPress and wordpress-develop are versioned together, and the test library only works against
# the core it shipped with, so "latest" has to be resolved to a number before either is fetched.
if [ "$WP_VERSION" = "latest" ]; then
	say "resolving the latest WordPress release"
	WP_VERSION=$(
		curl -fsSL 'https://api.wordpress.org/core/version-check/1.7/' |
			php -r '$j = json_decode(stream_get_contents(STDIN), true); echo $j["offers"][0]["current"];'
	)
fi
say "WordPress $WP_VERSION"

fetch_tarball() {
	local url=$1 dest=$2 strip=$3 subpath=${4:-}
	local tmp
	tmp=$(mktemp -d)
	curl -fsSL "$url" -o "$tmp/archive.tar.gz"
	mkdir -p "$dest"
	if [ -n "$subpath" ]; then
		tar -xzf "$tmp/archive.tar.gz" -C "$dest" --strip-components="$strip" "$subpath"
	else
		tar -xzf "$tmp/archive.tar.gz" -C "$dest" --strip-components="$strip"
	fi
	rm -rf "$tmp"
}

if [ ! -d "$WP_CORE_DIR/wp-includes" ]; then
	say "installing WordPress core into $WP_CORE_DIR"
	fetch_tarball "https://wordpress.org/wordpress-${WP_VERSION}.tar.gz" "$WP_CORE_DIR" 1
else
	say "WordPress core already present in $WP_CORE_DIR"
fi

if [ ! -d "$WP_TESTS_DIR/includes" ]; then
	say "installing the test library into $WP_TESTS_DIR"
	# wordpress-develop carries the suite at tests/phpunit; includes/ is the framework and data/ is
	# the fixture set several of its cases load.
	fetch_tarball \
		"https://github.com/WordPress/wordpress-develop/archive/refs/tags/${WP_VERSION}.tar.gz" \
		"$WP_TESTS_DIR" 3 "wordpress-develop-${WP_VERSION}/tests/phpunit"
else
	say "test library already present in $WP_TESTS_DIR"
fi

say "writing $WP_TESTS_DIR/wp-tests-config.php"
cat > "$WP_TESTS_DIR/wp-tests-config.php" <<PHP
<?php
/* Generated by bin/install-wp-tests.sh — safe to delete and regenerate. */

define( 'ABSPATH', '${WP_CORE_DIR}/' );

define( 'DB_NAME', '${DB_NAME}' );
define( 'DB_USER', '${DB_USER}' );
define( 'DB_PASSWORD', '${DB_PASS}' );
define( 'DB_HOST', '${DB_HOST}' );
define( 'DB_CHARSET', 'utf8' );
define( 'DB_COLLATE', '' );
\$table_prefix = 'wptests_';

/*
 * The plugin is loaded from the repository working tree, not copied into wp-content/plugins, so
 * that a local run tests the files you just edited. Pointing WP_PLUGIN_DIR at the tree is what
 * makes that honest: plugin_basename() strips this prefix, so NAULON_PLUGIN_FILE resolves to
 * 'naulon/naulon.php' — the same key get_plugins() and core's update loop use. Without it,
 * UpdaterCacheTest's pass through wp_update_plugins() would look for a plugin core cannot see.
 */
define( 'WP_PLUGIN_DIR', '${PLUGINS_ROOT}' );
define( 'WP_PLUGIN_URL', 'http://example.org/wp-content/plugins' );

define( 'WP_TESTS_DOMAIN', 'example.org' );
define( 'WP_TESTS_EMAIL', 'admin@example.org' );
define( 'WP_TESTS_TITLE', 'Test Blog' );
define( 'WP_PHP_BINARY', 'php' );
define( 'WP_DEFAULT_THEME', 'default' );
PHP

if [ "$SKIP_DB_CREATE" != "1" ]; then
	say "creating the database $DB_NAME"
	# mysqladmin is not always around (macOS, slim images) and PHP always is, since the suite needs
	# it anyway. One less thing to install.
	DB_NAME="$DB_NAME" DB_USER="$DB_USER" DB_PASS="$DB_PASS" DB_HOST="$DB_HOST" php -r '
		list( $host, $port ) = array_pad( explode( ":", getenv( "DB_HOST" ) ), 2, 3306 );
		$db = new mysqli( $host, getenv( "DB_USER" ), getenv( "DB_PASS" ), "", (int) $port );
		if ( $db->connect_error ) {
			fwrite( STDERR, "cannot reach MySQL at " . getenv( "DB_HOST" ) . ": {$db->connect_error}\n" );
			exit( 1 );
		}
		$name = $db->real_escape_string( getenv( "DB_NAME" ) );
		$db->query( "CREATE DATABASE IF NOT EXISTS `$name`" ) or exit( 1 );
	'
fi

say "ready — run: WP_TESTS_DIR=$WP_TESTS_DIR vendor/bin/phpunit -c phpunit-integration.xml.dist"
